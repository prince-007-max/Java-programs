import java.util.Scanner;

public class TimeComplexity {
    public static void main(String[] args) {
        
        Scanner sc = new Scanner(System.in);
        int n = sc.nextInt();

        System.out.println("O(1) Example: ");
        for (int i = 0; i < n; i++) {
            System.out.println();
        }

    }
}
